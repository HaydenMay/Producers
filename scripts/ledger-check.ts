// Ledger hygiene check (no game logic). Usage: npm run ledger:check
// 1. Every ledger row has a unique PROD-### id, a valid design status and a valid implementation state.
// 2. Every substantive entry of the 2026-11-10 decision audit (sections 1–15) is mapped to at least one ledger row.
// Writes docs/ledger-crosswalk.md (a verification aid, NOT a design authority) and exits non-zero on any problem.
import { readFileSync, writeFileSync } from "node:fs";

const LEDGER = "docs/DESIGN_LEDGER.md";
const AUDIT = "docs/archive/handoffs/Entertainment_Studio_Tycoon_Decision_Audit_2026-11-10.md";
const STATUSES = ["LOCKED", "TESTING", "OPEN", "LATER", "SUPERSEDED"];
const IMPLS = ["Implemented differently", "Implemented", "Partial", "Not implemented", "Unknown", "Process", "—"];

// audit entries: "- **[STATUS]**" bullets in sections 1–14, numbered items in section 15
const audit: { id: string; text: string }[] = [];
let sec = 0, n = 0;
for (const line of readFileSync(AUDIT, "utf8").split("\n")) {
  const m = line.match(/^## (\d+)\. /);
  if (m) {
    sec = Number(m[1]);
    n = 0;
    continue;
  }
  if (sec >= 1 && sec <= 14 && line.startsWith("- **[")) audit.push({ id: `A${sec}.${++n}`, text: line.slice(2, 140) });
  if (sec === 15 && /^\d+\. /.test(line)) audit.push({ id: `A${sec}.${++n}`, text: line.slice(0, 140) });
}

const problems: string[] = [];
const rows: { id: string; status: string; impl: string; refs: string[]; title: string }[] = [];
for (const line of readFileSync(LEDGER, "utf8").split("\n")) {
  const m = line.match(/^\| (PROD-\d{3}) \| (.*) \|$/);
  if (!m) continue;
  const cells = m[2].split(" | ");
  const refs = (cells.at(-1) ?? "").match(/A\d+\.\d+/g) ?? [];
  const superseded = cells.length === 4; // superseded table: old rule | status | replaced by | audit
  const status = superseded ? cells[1] : cells[1];
  const impl = superseded ? "—" : cells[2];
  rows.push({ id: m[1], status, impl, refs, title: cells[0].slice(0, 90) });
  if (!STATUSES.some((s) => status.startsWith(s))) problems.push(`${m[1]}: status "${status}" does not start with one of ${STATUSES.join("/")}`);
  if (!IMPLS.some((s) => impl.replace(/\*/g, "").startsWith(s))) problems.push(`${m[1]}: implementation "${impl.slice(0, 40)}" is not a known state`);
}
const ids = rows.map((r) => r.id);
const dup = ids.filter((x, i) => ids.indexOf(x) !== i);
if (dup.length) problems.push(`duplicate ids: ${[...new Set(dup)].join(", ")}`);
const nums = ids.map((x) => Number(x.slice(5))).sort((a, b) => a - b);
for (let i = 1; i < nums.length; i++) if (nums[i] !== nums[i - 1] + 1) problems.push(`gap between PROD-${nums[i - 1]} and PROD-${nums[i]} (ids are never recycled; note retired ids explicitly)`);

const mapped = new Map<string, string[]>();
for (const r of rows) for (const a of r.refs) mapped.set(a, [...(mapped.get(a) ?? []), r.id]);
const missing = audit.filter((a) => !mapped.has(a.id));
for (const a of missing) problems.push(`audit entry ${a.id} not mapped: ${a.text}`);
const unknownRefs = [...mapped.keys()].filter((k) => !audit.some((a) => a.id === k));
for (const k of unknownRefs) problems.push(`ledger cites ${k}, which is not an audit entry`);

const byStatus = Object.fromEntries(STATUSES.map((s) => [s, rows.filter((r) => r.status.startsWith(s)).length]));
const L = [
  "# Ledger ↔ audit crosswalk (generated by `npm run ledger:check`)",
  "",
  "> **Verification aid only, not a design authority.** The canonical design is `docs/DESIGN_LEDGER.md`.",
  "",
  `- Audit entries inventoried: **${audit.length}** (sections 1–14: ${audit.filter((a) => !a.id.startsWith("A15.")).length} decisions; section 15: ${audit.filter((a) => a.id.startsWith("A15.")).length} inconsistencies)`,
  `- Mapped to ledger rows: **${audit.length - missing.length}**; unmapped: **${missing.length}**`,
  `- Ledger rows: **${rows.length}** (${Object.entries(byStatus).map(([k, v]) => `${k} ${v}`).join(", ")}); ${rows.filter((r) => !r.refs.length).length} rows come from v9.6 / gate evidence with no audit line`,
  `- Problems: **${problems.length}**`,
  "",
  "Several audit entries map to one row where the audit repeated the same decision (e.g. A6.8 + A9.11 season announcements); a few audit entries split across rows.",
  "",
  "| Audit entry | Ledger rows | Audit text (start) |",
  "|---|---|---|",
  ...audit.map((a) => `| ${a.id} | ${(mapped.get(a.id) ?? ["**MISSING**"]).join(", ")} | ${a.text.replace(/\|/g, "/")} |`),
  "",
];
writeFileSync("docs/ledger-crosswalk.md", L.join("\n"));
console.log(`audit ${audit.length} entries, ${audit.length - missing.length} mapped; ledger ${rows.length} rows; ${problems.length} problems`);
for (const p of problems) console.log(`  - ${p}`);
process.exit(problems.length ? 1 : 0);
